PORTS = {"quick": 9931, "deep": 9932, "embed": 9933}


def llm_args(engine: str, gguf: str, ctx: int, threads: int, batch: int = 256, embed_seq: int = 512,
             pooling: str = "mean", reasoning_budget: bool = False) -> str:
    port = PORTS[engine]
    common = f"--host 127.0.0.1 --port {port} --api-key-file /etc/gladeon/llm_api_key -m {gguf} -t {threads} --mlock --no-webui"
    if engine == "embed":
        return f"{common} --embeddings --pooling {pooling} -np 2 -c {2 * embed_seq} -b {embed_seq} -ub {embed_seq}"
    extra = " --reasoning-budget 0" if reasoning_budget else ""
    return f"{common} -c {ctx} -np 1 -b {batch} -ub {batch} --jinja --cache-ram 256{extra}"


def render_all(c: NetConfig) -> dict[str, str]:
    files = {
        "/etc/nftables.conf": nftables(c),
        "/etc/sysctl.d/90-gladeon.conf": SYSCTL,
        "/etc/systemd/logind.conf.d/90-gladeon.conf": LOGIND,
        "/etc/systemd/coredump.conf.d/90-gladeon.conf": COREDUMP,
        "/etc/systemd/journald.conf.d/90-gladeon.conf": JOURNALD,
        "/etc/systemd/system/gladeon-proxy.service": PROXY_UNIT,
        "/etc/systemd/system/gladeon-proxy.service.d/ip.conf": proxy_ip_dropin(c),
        "/etc/systemd/system/gladeon-privd.service": PRIVD_UNIT,
        "/etc/systemd/system/gladeon-llm@.service": LLM_UNIT,
        "/etc/systemd/system/srv-gladeon-vault.mount": VAULT_MOUNT,
        "/etc/systemd/system/gladeon-wifi-tune.service": WIFI_TUNE,
        "/etc/systemd/system/gladeon-sync.service": SYNC_UNIT,
        "/etc/systemd/system/gladeon-sync.service.d/ip.conf": sync_ip_dropin(c),
    }
    for n, body in network_files(c).items():
        files[f"/etc/systemd/network/{n}"] = body
    for n, body in link_files(c).items():
        files[f"/etc/systemd/network/{n}"] = body
    return files
