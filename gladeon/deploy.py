"""Render the PC's system files from config (spec 4.2, 4.4, 5.2.1, 7.2-7.5, 8.4).
`gladeon-admin` writes these; nothing here touches the system by itself."""
from __future__ import annotations

import ipaddress
from dataclasses import dataclass


@dataclass
class NetConfig:
    phone_ip: str
    admin_ip: str
    pc_ip_eth: str           # with prefix, e.g. 192.168.1.10/24
    pc_ip_wlan: str
    gateway: str = ""        # router LAN address; WAN is unplugged
    eth_mac: str = ""
    wlan_mac: str = ""

    def __post_init__(self):
        for ip in (self.phone_ip, self.admin_ip):
            ipaddress.IPv4Address(ip)
        for net in (self.pc_ip_eth, self.pc_ip_wlan):
            ipaddress.IPv4Interface(net)


def nftables(c: NetConfig) -> str:
    return f"""#!/usr/sbin/nft -f
# Generated by gladeon-admin from config.json. Do not edit by hand (4.4).
flush ruleset
table inet gladeon {{
  chain input {{
    type filter hook input priority 0; policy drop;
    iif "lo" accept
    ct state established,related accept
    ct state invalid drop
    ip saddr {c.phone_ip} tcp dport 8443 accept
    ip saddr {c.phone_ip} tcp dport 22000 accept
    ip saddr {c.phone_ip} udp dport 22000 accept
    ip saddr {{ {c.phone_ip}, {c.admin_ip} }} tcp dport 22 accept
    ip saddr {c.phone_ip} icmp type echo-request accept
  }}
  chain forward {{
    type filter hook forward priority 0; policy drop;
  }}
  chain output {{
    type filter hook output priority 0; policy drop;
    oif "lo" accept
    ct state established,related accept
    ip daddr {c.phone_ip} tcp dport 22000 accept
    ip daddr {c.phone_ip} udp dport 22000 accept
  }}
}}
"""


def link_files(c: NetConfig) -> dict[str, str]:
    out = {}
    for name, mac in (("gleth0", c.eth_mac), ("glwlan0", c.wlan_mac)):
        if mac:
            out[f"10-{name}.link"] = f"[Match]\nMACAddress={mac}\n\n[Link]\nName={name}\n"
    return out


def network_files(c: NetConfig) -> dict[str, str]:
    def one(name: str, addr: str, metric: int) -> str:
        gw = f"\n[Route]\nGateway={c.gateway}\nMetric={metric}\n" if c.gateway else ""
        return (f"[Match]\nName={name}\n\n[Link]\nRequiredForOnline=no\n\n[Network]\nLinkLocalAddressing=no\n"
                f"IPv6AcceptRA=no\n\n[Address]\nAddress={addr}\nRouteMetric={metric}\n{gw}")
    return {"10-gleth0.network": one("gleth0", c.pc_ip_eth, 100),
            "10-glwlan0.network": one("glwlan0", c.pc_ip_wlan, 600)}


