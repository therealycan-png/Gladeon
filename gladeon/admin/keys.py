"""SSH key handling for gladeon-admin key-add / key-remove / phone-replace (3.3, 5.3).
Pure text logic: the caller writes the files atomically and runs update-initramfs."""
from __future__ import annotations

import base64
import binascii
import hashlib
import ipaddress
import json
import re
import struct
from dataclasses import dataclass

ROLES = ("phone", "admin")
DROPBEAR_OPTS = 'command="cryptroot-unlock",no-port-forwarding,no-agent-forwarding,no-X11-forwarding'
SSHD_OPTS = "no-port-forwarding,no-agent-forwarding,no-X11-forwarding"
_DEVICE_ID_RE = re.compile(r"^[A-Z2-7]{7}(-[A-Z2-7]{7}){7}$")


@dataclass(frozen=True)
class Key:
    role: str
    blob_b64: str          # the base64 key body only; comments and options from input are dropped

    @property
    def fingerprint(self) -> str:
        """Same as `ssh-keygen -lf`: SHA256:<base64 without padding>."""
        d = hashlib.sha256(base64.b64decode(self.blob_b64)).digest()
        return "SHA256:" + base64.b64encode(d).decode().rstrip("=")


def parse_pubkey(role: str, text: str) -> Key:
    if role not in ROLES:
        raise ValueError("BAD_ROLE")
    parts = text.strip().split()
    if len(parts) < 2 or parts[0] != "ssh-ed25519":
        raise ValueError("ED25519_ONLY")              # options or other key types are refused
    try:
        blob = base64.b64decode(parts[1], validate=True)
    except (binascii.Error, ValueError):
        raise ValueError("BAD_KEY") from None
    try:
        (n,) = struct.unpack(">I", blob[:4])
        kind = blob[4:4 + n]
        (m,) = struct.unpack(">I", blob[4 + n:8 + n])
        raw = blob[8 + n:8 + n + m]
    except struct.error:
        raise ValueError("BAD_KEY") from None
    if kind != b"ssh-ed25519" or m != 32 or len(raw) != 32 or 8 + n + m != len(blob):
        raise ValueError("BAD_KEY")
    return Key(role, parts[1])


def load(text: str) -> list[Key]:
    return [Key(d["role"], d["key"]) for d in json.loads(text or "[]")]


def dump(keys: list[Key]) -> str:
    return json.dumps([{"role": k.role, "key": k.blob_b64} for k in keys], indent=1)


def add(keys: list[Key], new: Key) -> list[Key]:
    if any(k.blob_b64 == new.blob_b64 for k in keys):
        return list(keys)                              # idempotent
    return list(keys) + [new]


def remove(keys: list[Key], fingerprint: str) -> list[Key]:
    left = [k for k in keys if k.fingerprint != fingerprint]
    if len(left) == len(keys):
        raise ValueError("NO_SUCH_KEY")
    if not left:
        raise ValueError("LAST_KEY")                   # never lock out every admin path
    return left


def authorized_keys(keys: list[Key], phone_ip: str, admin_ip: str) -> str:
    ipaddress.IPv4Address(phone_ip)
    ipaddress.IPv4Address(admin_ip)
    out = ["# Generated by gladeon-admin. Do not edit by hand."]
    for k in keys:
        frm = phone_ip if k.role == "phone" else f"{phone_ip},{admin_ip}"
        out.append(f'from="{frm}",{SSHD_OPTS} ssh-ed25519 {k.blob_b64} gladeon-{k.role}')
    return "\n".join(out) + "\n"


def dropbear_keys(keys: list[Key]) -> str:
    """Initramfs unlock keys: forced command, no from= (3.2.4)."""
    out = [f"{DROPBEAR_OPTS} ssh-ed25519 {k.blob_b64} gladeon-{k.role}" for k in keys]
    return "\n".join(out) + "\n"


def check_dropbear(text: str) -> bool:
    """selfcheck: every key line carries the forced command and no from=."""
    lines = [ln for ln in text.splitlines() if ln.strip() and not ln.startswith("#")]
    return bool(lines) and all(ln.startswith('command="cryptroot-unlock"') and "from=" not in ln for ln in lines)


def valid_device_id(s: str) -> bool:
    return bool(_DEVICE_ID_RE.match(s))
